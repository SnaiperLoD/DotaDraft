function withMatchIds(bracket: TiBracket): TiBracket {
  const byNode = (matchIdMap as Record<string, Record<string, string[]>>)[bracket.id] ?? {};
  return {
    ...bracket,
    matches: bracket.matches.map((match) => ({
      ...match,
      matchIds: byNode[match.id] ?? match.matchIds,
    })),
  };
}

export const TI_BRACKETS: TiBracket[] = RAW_TI_BRACKETS.map(withMatchIds);

export function tiBracketById(id: string): TiBracket | undefined {
  return TI_BRACKETS.find((b) => b.id === id);
}
